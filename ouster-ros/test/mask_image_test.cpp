Bytes text(const std::string& value) { return Bytes(value.begin(), value.end()); }

Bytes join(Bytes head, const Bytes& tail) {
    head.insert(head.end(), tail.begin(), tail.end());
    return head;
}

// A file that exists for the lifetime of one test.
class TempFile {
   public:
    explicit TempFile(const Bytes& content) {
        static int serial = 0;
        path_ = testing::TempDir() + "mask_image_test_" +
                std::to_string(::getpid()) + "_" + std::to_string(serial++);
        std::ofstream file(path_, std::ios::binary);
        file.write(reinterpret_cast<const char*>(content.data()),
                   static_cast<std::streamsize>(content.size()));
    }
    ~TempFile() { std::remove(path_.c_str()); }
    const std::string& path() const { return path_; }

   private:
    std::string path_;
};

MaskImage read(const Bytes& content) {
    TempFile file(content);
    return read_mask_image(file.path());
}

void expect_mask(const MaskImage& image, size_t rows, size_t cols,
                 const Flags& keep) {
    EXPECT_EQ(image.rows, rows);
    EXPECT_EQ(image.cols, cols);
    EXPECT_EQ(image.keep, keep);
}

MaskImage ramp(size_t cols) {
    MaskImage image;
    image.rows = 1;
    image.cols = cols;
    image.keep.resize(cols);
    return image;
}

// The source column each destination column reads when a 1 x source image is
// fitted to 1 x destination: mark one source column at a time and see where
// it lands.
std::vector<size_t> sampled_columns(size_t source, size_t destination) {
    std::vector<size_t> columns(destination, source);
    for (size_t marked = 0; marked < source; ++marked) {
        MaskImage image = ramp(source);
        image.keep[marked] = 1;
        const auto fitted = resize_mask(image, 1, destination);
        for (size_t i = 0; i < destination; ++i)
            if (fitted[i]) columns[i] = marked;
    }
    return columns;
}

